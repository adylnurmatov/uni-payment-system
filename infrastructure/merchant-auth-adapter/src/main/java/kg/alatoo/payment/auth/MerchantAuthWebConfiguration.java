package kg.alatoo.payment.auth;

import org.springframework.context.annotation.Configuration;
import org.springframework.web.method.support.HandlerMethodArgumentResolver;
import org.springframework.web.servlet.config.annotation.WebMvcConfigurer;

import java.util.List;

@Configuration
public class MerchantAuthWebConfiguration implements WebMvcConfigurer {
    private final CurrentMerchantArgumentResolver resolver;

    public MerchantAuthWebConfiguration(CurrentMerchantArgumentResolver resolver) {
        this.resolver = resolver;
    }

    @Override
    public void addArgumentResolvers(List<HandlerMethodArgumentResolver> resolvers) {
        resolvers.add(resolver);
    }
}
