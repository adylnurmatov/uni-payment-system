package kg.alatoo.payment.models;

/**
 * Статус транзакции в блокчейне, как его видит бизнес-логика (без деталей конкретной сети).
 */
public enum TransactionStatus {
    /** Транзакция отправлена, но ещё не попала в блок (нет receipt). */
    PENDING,
    /** Транзакция в блоке и выполнена успешно. */
    SUCCESS,
    /** Транзакция в блоке, но откатилась (reverted). */
    FAILED
}
